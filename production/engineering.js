import { knob, sim } from './sim-core.js';

const format = new Intl.NumberFormat('pt-BR', { maximumFractionDigits: 2 });
const display = (value, unit) => format.format(value) + ' ' + unit;
const count = (label, initial, max = 20, unit = 'casos') => knob(label, unit, 0, max, 1, initial);
const quantity = (label, initial, max, unit) => knob(label, unit, 1, max, 1, initial);

function stage(label, title, nodes, body, knobs, calculate, results, rule, code) {
  const metrics = results.map(([name, unit]) => [name, unit]);
  const inputs = knobs.map((k) => k.initial);
  const current = calculate(...inputs);
  const alternate = calculate(knobs[0].max, ...inputs.slice(1));
  const changed = alternate.findIndex((value, i) => value !== current[i]);
  const metric = changed < 0 ? 0 : changed;
  const [name, unit] = metrics[metric];
  return {
    step: {
      label,
      title,
      nodes: nodes.split('|'),
      active: 1,
      body,
      code,
      metrics: metrics.map(([key, u], i) => [key, display(current[i], u)]),
      change: metrics.map(([key, u], i) => key.toLowerCase() + ' ' + display(current[i], u)).join(' e ') + '.',
      idea: rule,
    },
    decision: [
      title,
      nodes.split('|')[1],
      nodes.split('|')[2],
      name,
      display(alternate[metric], unit),
      display(current[metric], unit),
      rule,
    ],
    model: sim('fluxo', knobs, calculate, metrics, rule),
    illustrate: (_, readings) =>
      results.map(([name, unit, shape], i) => ({ label: name, unit, shape, value: readings[i] })),
  };
}

// All counts below describe the fixture. Each edit reruns the same small model.
function partition(label, title, nodes, body, limit, input, initial, yes, no, rule, code) {
  return stage(
    label,
    title,
    nodes,
    body,
    [count(input, initial, limit)],
    (n) => [n, limit - n],
    [
      [yes, 'casos', 'check'],
      [no, 'casos', 'request'],
    ],
    rule,
    code,
  );
}

function batches(label, title, nodes, body, first, second, results, rule, code) {
  return stage(
    label,
    title,
    nodes,
    body,
    [first, second],
    (a, b) => [a * b, a],
    [results[0], results[1]],
    rule,
    code,
  );
}

